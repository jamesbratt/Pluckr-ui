const constructSFQLQuery = (params, resource) => {
  if (!params) {
    throw Error('You must select some fields');
  }

  let query = 'SELECT';
  params.value.forEach((param, index) => {
    const endComma = index === params.value.length -1 ? '' : ',';
    query += `+${param}${endComma}`
  });
  return `${query}+FROM+${resource}`; 
}

const doSalesforceQuery = (params, resource, username, apiKey, sourceId) => {
  const query = constructSFQLQuery(params.find(params => params.name === 'fields'), resource);
  const key = getToken(INTEGRATION_TYPE);
  const url = `${SALESFORCE_URI}/services/data/v40.0/query?q=${query}`;
  return proxyRequest(url, key, INTEGRATION_TYPE, username, apiKey, sourceId);
};

export const getSalesforceData = (resource, params, username, apiKey, sourceId = null) => {
  let call;
  switch(resource) {
    case SALESFORCE_RESOURCES.lead.name:
    case SALESFORCE_RESOURCES.campaign.name:
    case SALESFORCE_RESOURCES.opportunity.name:
    case SALESFORCE_RESOURCES.contact.name:
    case SALESFORCE_RESOURCES.account.name:
    case SALESFORCE_RESOURCES.case.name:
    call = doSalesforceQuery;
        break;
  default:
    console.error('Invalid');
    break;
  }
  return call(params, resource, username, apiKey, sourceId)
  .then(response => {
    return {
      sourceId,
      data: response,
      properties: null,
    }
  }) 
};